import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const outdir = path.join(root, 'supabase/functions/scraper-builder');
await mkdir(outdir, { recursive: true });
const result = await build({
    absWorkingDir: root,
    entryPoints: ['scripts/builder/edgeEntry.ts'],
    outfile: path.join(outdir, 'index.js'),
    bundle: true,
    minify: true,
    format: 'esm',
    platform: 'node',
    target: 'es2022',
    metafile: true,
    banner: {
        js: '// Generated by npm run build:builder-edge. Edit scripts/builder, not this file.\nimport { createRequire } from "node:module"; import { fileURLToPath } from "node:url"; import { dirname } from "node:path"; const require = createRequire(import.meta.url); const __filename = fileURLToPath(import.meta.url); const __dirname = dirname(__filename);',
    },
    plugins: [
        {
            name: 'edge-browser-disabled',
            setup(build) {
                build.onResolve({ filter: /scraperBrowser$/ }, () => ({
                    path: 'browser-disabled',
                    namespace: 'edge',
                }));
                build.onLoad({ filter: /.*/, namespace: 'edge' }, () => ({
                    contents:
                        'export async function launchScraperBrowser() { throw new Error("Browser inspection requires the local companion"); }',
                    loader: 'js',
                }));
            },
        },
    ],
});
if (
    Object.keys(result.metafile.inputs).some((name) =>
        /playwright|puppeteer|builder[\\/]checks\.ts|builder[\\/]server\.ts/.test(
            name
        )
    )
)
    throw new Error(
        'An unsupported local dependency entered the Edge Function bundle'
    );
console.log(
    `Built scraper-builder Edge Function (${(Object.values(result.metafile.outputs).reduce((total, output) => total + output.bytes, 0) / 1024 / 1024).toFixed(2)} MB); browser and repository check modules excluded.`
);
