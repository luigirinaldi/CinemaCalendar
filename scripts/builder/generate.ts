import { parse } from 'node-html-parser';
import type { GeneratedFiles, ScraperConfig } from '../../shared/scraperConfig';
import {
    configuredJson,
    parseConfiguredProgramme,
    valueAt,
    readHybridCapture,
    configuredFilmUrls,
} from '../configuredScraper';

export function fixtureBody(config: ScraperConfig, body: string): string {
    if (config.details) {
        const capture = readHybridCapture(body);
        const empty = { path: '', attribute: '' };
        const metadata = fixtureBody(
            {
                ...config,
                details: undefined,
                start: empty,
                date: empty,
                booking: empty,
            },
            JSON.stringify(capture.programme)
        );
        const urls = configuredFilmUrls(config, metadata);
        return JSON.stringify({
            ...capture,
            programme: JSON.parse(metadata),
            pages: Object.fromEntries(
                urls.map((url) => [url, capture.pages[url]])
            ),
        });
    }
    // Page/ancestor mappings and embedded JSON need their surrounding document.
    // Keep the full source within the existing fixture size bound rather than
    // silently removing a date heading that lives outside the film card.
    if (
        config.embeddedJson ||
        [
            config.title,
            config.filmUrl,
            config.director,
            config.poster,
            config.start,
            config.date,
            config.booking,
        ].some((field) => field.scope === 'page' || field.scope === 'ancestor')
    )
        return body;
    if (config.mode === 'html')
        return parse(body)
            .querySelectorAll(config.items)
            .slice(0, 3)
            .map((element) => element.outerHTML)
            .join('\n');
    const source: unknown = configuredJson(body, config);
    const items = valueAt(source, config.items);
    if (!Array.isArray(items))
        throw new Error('Choose the JSON array containing films');
    if (config.items === '$') return JSON.stringify(items.slice(0, 3));
    const root: Record<string, unknown> = {};
    const parts = config.items.split('.');
    let parent = root;
    for (const key of parts.slice(0, -1)) {
        const child = {};
        parent[key] = child;
        parent = child;
    }
    parent[parts.at(-1)!] = items.slice(0, 3);
    return JSON.stringify(root);
}
export function generateFiles(
    config: ScraperConfig,
    body: string
): GeneratedFiles {
    const fixture = fixtureBody(config, body);
    const expected = parseConfiguredProgramme(config, fixture);
    if (fixture.length > 200000)
        throw new Error(
            'The selected fixture exceeds 200 KB. Use a more specific film selector.'
        );
    const identifier = config.filename.replace(/\.ts$/, '');
    return {
        scraperPath: `scripts/cinemas/${config.filename}`,
        scraper: `// Generated by the cinema scraper builder; review mappings before merging.\nimport type { ScraperConfig } from '../../shared/scraperConfig';\nimport { parseConfiguredProgramme, runConfiguredScraper } from '../configuredScraper';\n\nexport const config = ${JSON.stringify(config, null, 4)} satisfies ScraperConfig;\n\nexport const parseProgramme = (body: string) => parseConfiguredProgramme(config, body);\nexport const scraper = () => runConfiguredScraper(config);\n`,
        testPath: `tests/${identifier}.test.ts`,
        test: `import test from 'node:test';\nimport assert from 'node:assert/strict';\nimport { parseProgramme } from '../scripts/cinemas/${identifier}';\n\n// Public programme captured during onboarding; tests make no live requests.\nconst fixture = ${JSON.stringify(fixture)};\nconst expected = ${JSON.stringify(expected, null, 4)};\n\ntest(${JSON.stringify(`${config.cinema.name}: fixture preserves titles, timezone conversion and booking URLs`)}, () => {\n    assert.deepEqual(JSON.parse(JSON.stringify(parseProgramme(fixture))), expected);\n});\n`,
    };
}
